export function getAnimalById(id: string): Animal | undefined {
  return animals.find(a => a.id === id);
}

export function getAnimalsByCategory(category: string): Animal[] {
  return animals.filter(a => a.category === category);
}

export function getAnimalsByHabitat(habitat: string): Animal[] {
  return animals.filter(a => a.habitat.includes(habitat as any));
}

export function getAnimalsByRarity(rarity: string): Animal[] {
  return animals.filter(a => a.rarity === rarity);
}
